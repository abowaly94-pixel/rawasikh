import { useMemo } from "react";
import { CheckCircle2, Sparkles } from "lucide-react";
import { cn } from "@/lib/utils";
import {
  articleAnchorId,
  collectFootnotes,
  collectReferences,
  createInlineContext,
  referenceDisplayKey,
  renderArticleInline,
  type ArticleAlign,
  type ArticleBlock,
  type ArticleDecorationBlock,
} from "@/lib/articleBlocks";

interface Props {
  blocks: ArticleBlock[];
  className?: string;
}

const alignToJustify = (align: ArticleAlign) =>
  align === "center" ? "justify-center" : align === "left" ? "justify-end" : "justify-start";

const ruleAlignClass = (align: ArticleAlign) =>
  align === "center" ? "mx-auto" : align === "left" ? "ms-auto" : "me-auto";

const DecorationView = ({ block }: { block: ArticleDecorationBlock }) => {
  const width = block.size === "sm" ? 140 : block.size === "lg" ? 360 : 240;
  const height = block.size === "sm" ? 14 : block.size === "lg" ? 24 : 18;
  const strokeWidth = block.size === "sm" ? 1.2 : block.size === "lg" ? 1.8 : 1.5;

  return (
    <div
      className={cn("my-7 flex w-full items-center", alignToJustify(block.align))}
      style={{ color: block.color }}
      aria-hidden="true"
    >
      {block.shape === "line" && (
        <svg width={width} height={height} viewBox={`0 0 ${width} ${height}`} fill="none">
          <line
            x1="0"
            y1={height / 2}
            x2={width}
            y2={height / 2}
            stroke="currentColor"
            strokeWidth={strokeWidth}
            strokeLinecap="round"
            opacity="0.75"
          />
        </svg>
      )}

      {block.shape === "divider" && (
        <svg width={width} height={height} viewBox={`0 0 ${width} ${height}`} fill="none">
          <line
            x1="0"
            y1={height / 2}
            x2={width / 2 - 10}
            y2={height / 2}
            stroke="currentColor"
            strokeWidth={strokeWidth}
            strokeLinecap="round"
            opacity="0.55"
          />
          <line
            x1={width / 2 + 10}
            y1={height / 2}
            x2={width}
            y2={height / 2}
            stroke="currentColor"
            strokeWidth={strokeWidth}
            strokeLinecap="round"
            opacity="0.55"
          />
          <g transform={`rotate(45 ${width / 2} ${height / 2})`}>
            <rect
              x={width / 2 - 4}
              y={height / 2 - 4}
              width="8"
              height="8"
              fill="currentColor"
              opacity="0.85"
            />
          </g>
        </svg>
      )}

      {block.shape === "arrow" && (
        <svg width={width} height={height} viewBox={`0 0 ${width} ${height}`} fill="none">
          <line
            x1={width}
            y1={height / 2}
            x2="9"
            y2={height / 2}
            stroke="currentColor"
            strokeWidth={strokeWidth}
            strokeLinecap="round"
          />
          <path
            d={`M 15 ${height / 2 - 5} L 8 ${height / 2} L 15 ${height / 2 + 5}`}
            stroke="currentColor"
            strokeWidth={strokeWidth}
            strokeLinecap="round"
            strokeLinejoin="round"
          />
        </svg>
      )}

      {block.shape === "ornament" && (
        <div className="flex items-center gap-4" style={{ fontSize: height }}>
          <span className="h-px w-16 bg-current opacity-30" />
          <span className="leading-none tracking-[0.4em]">✦</span>
          <span className="h-px w-16 bg-current opacity-30" />
        </div>
      )}

      {block.shape === "dots" && (
        <div className="flex items-center gap-2.5" style={{ fontSize: height }}>
          <span className="h-1.5 w-1.5 rounded-full bg-current opacity-70" />
          <span className="h-1.5 w-1.5 rounded-full bg-current opacity-45" />
          <span className="h-1.5 w-1.5 rounded-full bg-current opacity-70" />
        </div>
      )}
    </div>
  );
};

/**
 * Public, read-only renderer for structured article blocks. Used by the
 * Arabic article page; other languages keep using the translated HTML
 * generated by `blocksToHtml`.
 */
const ArticleBlocks = ({ blocks, className }: Props) => {
  const context = useMemo(() => createInlineContext(blocks), [blocks]);
  const footnotes = useMemo(() => collectFootnotes(blocks), [blocks]);
  const references = useMemo(() => collectReferences(blocks), [blocks]);

  if (!blocks.length) return null;

  return (
    <div id="article-body" className={cn("article-blocks", className)} dir="rtl">
      {blocks.map((block) => {
        switch (block.type) {
          case "heading": {
            if (!block.text.trim()) return null;
            if (block.level === 2) {
              return (
                <div key={block.id} className="mt-10 mb-4 scroll-mt-28" style={{ textAlign: block.align }}>
                  <h2
                    className="text-2xl font-bold leading-[1.6] text-ink md:text-[28px]"
                    dangerouslySetInnerHTML={{ __html: renderArticleInline(block.text, context) }}
                  />
                  <span
                    className={cn("mt-2 block h-[2px] w-16 rounded-full bg-gold/60", ruleAlignClass(block.align))}
                  />
                </div>
              );
            }
            return (
              <h3
                key={block.id}
                className="mt-7 mb-3 scroll-mt-28 text-xl font-bold leading-[1.6] text-ink"
                style={{ textAlign: block.align }}
                dangerouslySetInnerHTML={{ __html: renderArticleInline(block.text, context) }}
              />
            );
          }

          case "paragraph": {
            if (!block.text.trim()) return null;
            return (
              <p
                key={block.id}
                className="mb-5 whitespace-pre-line text-[16.5px] leading-[2.05] text-foreground/85"
                style={{ textAlign: block.align }}
                dangerouslySetInnerHTML={{ __html: renderArticleInline(block.text, context) }}
              />
            );
          }

          case "list": {
            const items = block.items.filter((item) => item.trim());
            if (!items.length) return null;
            const ListTag = block.ordered ? "ol" : "ul";
            return (
              <ListTag
                key={block.id}
                className={cn(
                  "mb-5 space-y-1.5 whitespace-pre-line ps-7 text-[16.5px] leading-[1.95] text-foreground/85 marker:text-gold",
                  block.ordered ? "list-decimal" : "list-disc",
                )}
                style={block.ordered ? { listStyleType: block.numbering === "arabic" ? "arabic-indic" : "decimal" } : undefined}
              >
                {items.map((item, index) => (
                  <li
                    key={index}
                    dangerouslySetInnerHTML={{ __html: renderArticleInline(item, context) }}
                  />
                ))}
              </ListTag>
            );
          }

          case "table": {
            if (
              !block.headers.some((header) => header.trim()) &&
              !block.rows.some((row) => row.some((cell) => cell.trim()))
            ) {
              return null;
            }
            return (
              <div
                key={block.id}
                className="my-8 overflow-hidden rounded-xl border border-border shadow-sm"
                dir="auto"
              >
                <div className="overflow-x-auto">
                  <table className="w-full min-w-[640px] border-collapse text-start text-[13.5px] leading-7">
                    {block.caption.trim() && (
                      <caption className="caption-top pb-2 text-sm text-muted-foreground">
                        <span dangerouslySetInnerHTML={{ __html: renderArticleInline(block.caption, context) }} />
                      </caption>
                    )}
                    <thead>
                      <tr className="bg-ink text-white">
                        {block.headers.map((header, col) => (
                          <th
                            key={col}
                            className="border border-white/15 px-4 py-3 text-center align-top font-bold"
                            dangerouslySetInnerHTML={{ __html: renderArticleInline(header, context) }}
                          />
                        ))}
                      </tr>
                    </thead>
                    <tbody>
                      {block.rows.map((row, rowIndex) => (
                        <tr key={rowIndex} className={rowIndex % 2 === 1 ? "bg-muted/50" : "bg-card"}>
                          {row.map((cell, col) => (
                            <td
                              key={col}
                              className="whitespace-pre-line border border-border px-4 py-3 align-top text-muted-foreground"
                              dangerouslySetInnerHTML={{ __html: renderArticleInline(cell, context) }}
                            />
                          ))}
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              </div>
            );
          }

          case "footnotes": {
            const blockNotes = footnotes.filter((note) => note.blockId === block.id);
            if (!blockNotes.length) return null;
            return (
              <section
                key={block.id}
                className="mt-12 scroll-mt-28 rounded-2xl border border-border bg-muted/30 p-5 md:p-6"
              >
                <h3
                  className="mb-4 text-lg font-bold text-ink"
                  dangerouslySetInnerHTML={{ __html: renderArticleInline(block.title || "الهوامش", context) }}
                />
                <ol
                  start={blockNotes[0].number}
                  className="space-y-3 text-[14px] leading-8 text-muted-foreground"
                  style={{
                    listStyleType: block.numbering === "arabic" ? "arabic-indic" : "decimal",
                  }}
                >
                  {blockNotes.map((note) => {
                    const anchor = articleAnchorId(note.id);
                    return (
                      <li key={note.id} id={`fn-${anchor}`} className="scroll-mt-28">
                        <span dangerouslySetInnerHTML={{ __html: renderArticleInline(note.text, context) }} />{" "}
                        <a
                          href={`#fnref-${anchor}`}
                          className="text-primary no-underline hover:underline"
                          title="العودة إلى موضع الهامش"
                        >
                          ↩
                        </a>
                      </li>
                    );
                  })}
                </ol>
              </section>
            );
          }

          case "references": {
            const blockRefs = references.filter((ref) => ref.blockId === block.id);
            if (!blockRefs.length) return null;
            return (
              <section key={block.id} className="mt-12 scroll-mt-28 border-t border-border pt-8">
                <h3
                  className="mb-4 text-lg font-bold text-ink"
                  dangerouslySetInnerHTML={{ __html: renderArticleInline(block.title || "المراجع", context) }}
                />
                {block.intro?.trim() && (
                  <p
                    className="mb-3 text-[13.5px] leading-7 text-muted-foreground"
                    dangerouslySetInnerHTML={{ __html: renderArticleInline(block.intro, context) }}
                  />
                )}
                {block.groups.map((group) => {
                  const groupRefs = blockRefs.filter((ref) => ref.groupId === group.id);
                  if (!groupRefs.length) return null;
                  return (
                    <div key={group.id} className="mt-5">
                      {group.title.trim() && (
                        <h4
                          className="mb-2 text-sm font-bold text-gold-strong"
                          dangerouslySetInnerHTML={{ __html: renderArticleInline(group.title, context) }}
                        />
                      )}
                      <ol
                        start={groupRefs[0].number}
                        className="space-y-1 whitespace-pre-line text-[14px] leading-8 text-muted-foreground"
                        style={{
                          listStyleType: block.numbering === "arabic" ? "arabic-indic" : "decimal",
                        }}
                      >
                        {groupRefs.map((ref) => {
                          const anchor = articleAnchorId(ref.id);
                          return (
                            <li key={ref.id} id={`ref-${anchor}`} className="scroll-mt-28">
                              <span className="font-semibold text-foreground/80">
                                {referenceDisplayKey(ref)}
                              </span>
                              <span className="mx-1.5 text-border">—</span>
                              <span
                                dangerouslySetInnerHTML={{ __html: renderArticleInline(ref.text, context) }}
                              />
                            </li>
                          );
                        })}
                      </ol>
                    </div>
                  );
                })}
              </section>
            );
          }

          case "summary": {
            if (!block.text.trim()) return null;
            return (
              <aside
                key={block.id}
                className="my-8 rounded-2xl border border-gold/30 bg-gold-soft/30 p-6"
              >
                <div className="mb-3 flex items-center gap-2 text-lg font-bold text-gold-strong">
                  <Sparkles className="h-5 w-5" />
                  <span
                    dangerouslySetInnerHTML={{
                      __html: renderArticleInline(block.title || "الخلاصة", context),
                    }}
                  />
                </div>
                <div
                  className="whitespace-pre-line text-[16px] leading-8 text-foreground/85"
                  dangerouslySetInnerHTML={{ __html: renderArticleInline(block.text, context) }}
                />
              </aside>
            );
          }

          case "conclusion": {
            if (!block.text.trim()) return null;
            return (
              <section key={block.id} className="mt-10 border-t border-border pt-8">
                <h2 className="mb-4 flex items-center gap-2 text-2xl font-bold text-ink">
                  <CheckCircle2 className="h-6 w-6 text-gold" />
                  <span
                    dangerouslySetInnerHTML={{
                      __html: renderArticleInline(block.title || "الخاتمة", context),
                    }}
                  />
                </h2>
                <div
                  className="whitespace-pre-line text-[16.5px] leading-[2.05] text-foreground/85"
                  dangerouslySetInnerHTML={{ __html: renderArticleInline(block.text, context) }}
                />
              </section>
            );
          }

          case "decoration":
            return <DecorationView key={block.id} block={block} />;

          default:
            return null;
        }
      })}
    </div>
  );
};

export default ArticleBlocks;

/** Kept next to the renderer so the editor can show a true preview shape. */
export { DecorationView };
